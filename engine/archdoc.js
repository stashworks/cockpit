/* ARCHITECTURE.md - the tagging matrix as a document a person (or an AI without Cockpit) can read, generated from
   plugins/architecture/tags.json (Phase 5, item 1). The schema changes by ticket only; the file carries the schema
   version in its first line, so a project on an older version is a finding until the doc is regenerated.

   Cockpit writes it into a project only when the file is missing or carries Cockpit's own marker - a hand-written
   ARCHITECTURE.md is never touched (it is reported instead, with the way to regenerate). */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const MARK = '<!-- generated by Cockpit from plugins/architecture/tags.json v';
function matrix() { return JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'plugins', 'architecture', 'tags.json'), 'utf8')); }
function versionOf(text) { const m = new RegExp(MARK.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(\\d+)').exec(text || ''); return m ? Number(m[1]) : null; }

function render(m) {
  const L = [];
  const str = (v) => Array.isArray(v) ? v.join('; ') : v == null ? '' : typeof v === 'string' ? v : JSON.stringify(v);
  L.push(MARK + m.version + ' - the schema lives in tags.json and changes by ticket; regenerate this file, never edit it -->');
  L.push('# Architecture - how this code describes itself', '');
  L.push('Every source file says in its header what it is part of and what kind of thing it is; every feature has a README with its');
  L.push('purpose, its tables and its flows. That is the whole scheme, readable without any tool. Cockpit reads it - the map it draws');
  L.push('is only as true as these lines - and never edits it.', '');
  L.push('## The header', '');
  if (m.header) { L.push(str(m.header.syntax), ''); if (m.header.readFromLines) L.push('Read from the first ' + m.header.readFromLines + ' lines of the file.', ''); }
  L.push('## The tags', '');
  for (const [k, t] of Object.entries(m.tags || {})) {
    L.push('### @' + k + (t.required === true ? ' - required' : t.required ? ' - required ' + str(t.required) : t.declared === false ? ' - computed, never declared' : ' - optional'));
    if (t.appliesTo) L.push('- **on:** ' + str(t.appliesTo));
    if (t.usedFor) L.push('- **for:** ' + str(t.usedFor));
    if (t.values) L.push('- **values:** ' + str(t.values));
    if (t.where) L.push('- **where:** ' + str(t.where));
    if (t.verify) L.push('- **checked by:** ' + str(t.verify));
    if (t.changesBy) L.push('- **changes by:** ' + str(t.changesBy));
    L.push('');
  }
  if (m.kinds) { L.push('## The four kinds', ''); L.push('Values: ' + str(m.kinds.values) + (m.kinds.outside ? '; outside the shape: ' + str(m.kinds.outside) : ''), ''); if (m.kinds.rule) L.push('**Rule:** ' + m.kinds.rule, ''); if (m.kinds.why) L.push(m.kinds.why, ''); }
  if (m.readme) { L.push('## The feature README', ''); if (m.readme.path) L.push('At `' + m.readme.path + '`:'); for (const c of m.readme.contract || []) L.push('- ' + c); if (m.readme.why) L.push('', m.readme.why); L.push(''); }
  if (m.computedNotDeclared) { L.push('## Never declared - Cockpit computes these from the code', ''); if (m.computedNotDeclared.why) L.push(m.computedNotDeclared.why, ''); for (const x of m.computedNotDeclared.list || []) L.push('- ' + x); L.push(''); }
  if (m.findings) { L.push('## What the scan checks against the declarations', ''); for (const [k, v] of Object.entries(m.findings)) if (k[0] !== '_') L.push('- `' + k + '` - ' + str(v)); L.push(''); }
  L.push('## Tests, tickets, promotion', '');
  L.push('- Flows in a feature README are proven by tests that name them (`@flow`); Cockpit runs them on the test database after every change.');
  L.push('- A change enters through a ticket that declares the files it touches; the rescan verifies it; a person passes it before prod.');
  L.push('- Commits name the ticket (`#12: …`); that is how "which tickets touched this file" is computed. No ticket lists in headers.', '');
  L.push('_Schema version ' + m.version + '. Regenerate after a schema change: `node <cockpit>/cli.js <project> architecture-doc`._');
  return L.join('\n') + '\n';
}
/* write into a project when allowed; answer what happened */
function write(projectDir, force) {
  const m = matrix(); const file = path.join(projectDir, 'ARCHITECTURE.md');
  let old = null; try { old = fs.readFileSync(file, 'utf8'); } catch (e) { /* missing */ }
  const have = old === null ? null : versionOf(old);
  if (old !== null && have === null && !force) return { written: false, why: 'hand-written ARCHITECTURE.md - not touched', version: m.version, have: null };
  if (have === m.version && !force) return { written: false, why: 'current', version: m.version, have };
  fs.writeFileSync(file, render(m));
  return { written: true, version: m.version, have, why: old === null ? 'created' : 'regenerated from v' + have };
}
function status(projectDir) {
  const m = matrix(); let old = null; try { old = fs.readFileSync(path.join(projectDir, 'ARCHITECTURE.md'), 'utf8'); } catch (e) { /* */ }
  return { version: m.version, exists: old !== null, have: old === null ? null : versionOf(old), handWritten: old !== null && versionOf(old) === null };
}
module.exports = { render, write, status, matrix, versionOf, MARK };
